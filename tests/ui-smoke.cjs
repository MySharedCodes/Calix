const { chromium } = require(process.env.CALIX_PLAYWRIGHT || 'C:/Users/Numerical_Magic_Box/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');

const output = path.resolve('work/ui');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge', args: ['--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1360, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const responseFailures = [];
  page.on('response', response => { if (response.status() >= 400) responseFailures.push(`${response.status()} ${response.url()}`); });
  await page.goto(process.env.CALIX_URL || 'http://127.0.0.1:5173');
  await page.getByText('原生核心就绪').waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '全部运行', exact: true }).click();
  await page.locator('.cell').last().locator('.result-meta').first().waitFor({ timeout: 30000 });
  assert.equal(await page.locator('.error-message').count(), 0);
  await page.locator('.js-plotly-plot').first().waitFor();
  await page.screenshot({ path: path.join(output, 'notebook-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '计算示例' }).click();
  await page.getByRole('button', { name: '三维曲面', exact: true }).click();
  await page.locator('.cell-gutter button').last().click();
  await page.locator('.plot-canvas canvas').waitFor({ timeout: 30000 });
  const canvas = page.locator('.plot-canvas canvas').last();
  await canvas.scrollIntoViewIfNeeded();
  await page.waitForTimeout(1500);
  const pixels = await canvas.evaluate(canvas => {
    const gl = canvas.getContext('webgl2') || canvas.getContext('webgl');
    const data = new Uint8Array(4 * canvas.width * canvas.height);
    gl.readPixels(0, 0, canvas.width, canvas.height, gl.RGBA, gl.UNSIGNED_BYTE, data);
    let colored = 0;
    for (let i = 0; i < data.length; i += 4) if (Math.max(data[i], data[i+1], data[i+2]) - Math.min(data[i], data[i+1], data[i+2]) > 35) colored++;
    return { colored, total: canvas.width * canvas.height };
  });
  assert.ok(pixels.colored > pixels.total * 0.02, `3D plot is blank: ${JSON.stringify(pixels)}`);
  const before = await canvas.screenshot();
  const bounds = await canvas.boundingBox();
  await page.mouse.move(bounds.x + bounds.width * 0.45, bounds.y + bounds.height * 0.5);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * 0.7, bounds.y + bounds.height * 0.6, { steps: 15 }); await page.mouse.up();
  await page.waitForTimeout(600);
  const after = await canvas.screenshot();
  assert.ok(!before.equals(after), '3D orbit interaction did not change the image');
  await page.screenshot({ path: path.join(output, 'surface-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '关闭示例' }).click();
  await page.getByRole('button', { name: '计算单元', exact: true }).click();
  await page.locator('.formula-launch').last().click();
  const math = page.locator('math-field').last();
  await math.evaluate(mf => { mf.value = '\\frac{1}{3}+\\sqrt{2}'; mf.dispatchEvent(new InputEvent('input', { bubbles: true })); });
  await page.locator('.formula-composer').getByTitle('插入公式').click();
  await page.locator('.cell-gutter button').last().click();
  await page.locator('.cell').last().locator('.result-meta').first().waitFor();
  await page.locator('.formula-launch').last().click();
  assert.equal(await page.locator('.cell').last().locator('.error-message').count(), 0);
  await math.focus(); await page.keyboard.press('End'); await page.keyboard.press('Control+6');
  assert.ok((await math.evaluate(mf => mf.value)).includes('^'), 'Ctrl+6 did not insert a superscript');
  await math.evaluate(mf => { mf.value = ''; mf.dispatchEvent(new InputEvent('input', { bubbles: true })); mf.focus(); });
  await page.keyboard.press('Control+2');
  assert.ok((await math.evaluate(mf => mf.value)).includes('sqrt'), 'Ctrl+2 did not insert a radical');
  await page.getByRole('button', { name: '传统计算器面板', exact: true }).click();
  await page.getByLabel('计算器输入').fill('3[m]+20[cm]');
  await page.getByRole('button', { name: '=', exact: true }).click();
  await page.locator('.calculator-display .result-meta').waitFor();
  assert.equal(await page.locator('.calculator-display .error-message').count(), 0);
  await page.screenshot({ path: path.join(output, 'calculator-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'calculator-mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Calculator overflows mobile viewport');
  await page.getByRole('button', { name: '展开侧栏' }).click();
  await page.getByRole('button', { name: /^Notebook/ }).click();
  await page.getByRole('button', { name: '计算示例', exact: true }).click();
  await page.getByRole('button', { name: '收起侧栏' }).click();
  await page.getByRole('button', { name: '三维曲面', exact: true }).click();
  await page.locator('.cell-gutter button').last().click();
  if (await page.getByTitle('关闭示例').count()) await page.getByTitle('关闭示例').click();
  await page.locator('.plot-canvas canvas').waitFor();
  await page.locator('.plot-canvas canvas').scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(output, 'surface-mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Notebook overflows mobile viewport');
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ errors, responseFailures, pixels, status: 'passed' }, null, 2));
  assert.deepEqual(errors, []);
  assert.deepEqual(responseFailures, []);
  await browser.close();
  console.log('UI smoke passed: notebook, calculator, math input, shortcuts, 2D/3D plots, orbit, desktop/mobile.');
})().catch(error => { console.error(error); process.exit(1); });
