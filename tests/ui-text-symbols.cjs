const { chromium } = require(process.env.CALIX_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CALIX_BROWSER === 'chromium' ? {} : { channel: 'msedge' }) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
    const errors = []; page.on('pageerror', error => errors.push(String(error)));
    await page.goto(process.env.CALIX_URL || 'http://127.0.0.1:5187');
    await page.locator('.engine-status.ready').waitFor({ timeout: 30000 });
    assert.equal(await page.title(), 'Calix:开源、轻量、快捷的符号计算');
    const notebook = { format: 'calix-notebook', version: 1, title: 'Text symbols', cells: [{ mode: 'markdown', code: '# Heading\n\nSymbols: ' }] };
    await page.locator('input[type=file]').setInputFiles({ name: 'symbols.cixnb', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(notebook)) });
    await page.getByTitle('编辑文字单元', { exact: true }).click();
    const editor = page.locator('.rich-text-content');
    await editor.click(); await page.keyboard.press('Control+End');
    const insert = async alias => {
      await page.waitForFunction(() => document.activeElement?.isContentEditable || document.activeElement?.tagName === 'TEXTAREA');
      await page.keyboard.press('Escape');
      await page.getByLabel('特殊符号缩写', { exact: true }).fill(alias);
      await page.keyboard.press('Escape');
    };
    await insert('a');
    assert.match(await editor.innerText(), /α/);
    assert.equal(await page.locator('.symbol-input').count(), 0);
    await insert('does-not-exist');
    await page.getByRole('alert').waitFor();
    await page.getByLabel('特殊符号缩写', { exact: true }).fill(''); await page.keyboard.press('Escape');
    await insert('intt');
    await editor.locator('.tiptap-mathematics-render').click();
    await page.getByLabel('公式输入', { exact: true }).fill('\\int x\\,dx');
    await page.getByTitle('插入', { exact: true }).click();
    await page.getByTitle('预览文字单元', { exact: true }).click();
    assert.match(await page.locator('.markdown-content').innerText(), /α/);
    assert.equal(await page.locator('.markdown-content .katex-error').count(), 0);
    await page.getByTitle('编辑文字单元', { exact: true }).click();
    await page.getByTitle('Markdown 源码', { exact: true }).click();
    const source = page.locator('.markdown-cell textarea');
    await source.click(); await page.keyboard.press('Control+End');
    await insert('b');
    assert.match(await source.inputValue(), /β$/);
    await source.fill('# Heading\n\nleft REPLACE right');
    await source.evaluate(el => { const start = el.value.indexOf('REPLACE'); el.focus(); el.setSelectionRange(start, start + 7); });
    await insert('g');
    assert.equal(await source.inputValue(), '# Heading\n\nleft γ right');
    await page.keyboard.press('Control+End'); await insert('sum');
    assert.match(await source.inputValue(), /\$\\sum_/);
    await page.getByTitle('预览文字单元', { exact: true }).click();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: '保存', exact: true }).last().click();
    const download = await downloadPromise;
    const out = path.resolve('work/ui-text-symbols'); fs.mkdirSync(out, { recursive: true });
    const file = path.join(out, 'symbols.cixnb'); await download.saveAs(file);
    const saved = JSON.parse(fs.readFileSync(file, 'utf8'));
    assert.match(saved.cells[0].code, /left γ right/);
    assert.match(saved.cells[0].code, /\\sum_/);
    await page.getByRole('button', { name: '偏好设置', exact: true }).click();
    await page.getByLabel('界面语言', { exact: true }).selectOption('en');
    await page.waitForFunction(() => document.title === 'Calix: Open-source, lightweight, fast symbolic computation');
    await page.getByLabel('Language', { exact: true }).selectOption('zh');
    await page.waitForFunction(() => document.title === 'Calix:开源、轻量、快捷的符号计算');
    assert.deepEqual(errors, []);
    console.log('Text Esc symbols: rich text, formulas, source selection, unknown aliases, persistence and translated title passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
