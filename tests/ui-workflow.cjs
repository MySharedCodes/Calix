const { chromium } = require(process.env.CALIX_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1360, height: 1000 }, acceptDownloads: true });
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(process.env.CALIX_URL || 'http://127.0.0.1:5173');
  await page.getByText('原生核心就绪').waitFor({ timeout: 30000 });
  const labels = await page.locator('.sidebar .workspace-label').allTextContents();
  assert.deepEqual(labels, ['文件', '工作空间']);
  const tools = await page.locator('.toolbar-group button').allTextContents();
  assert.deepEqual(tools.slice(-2), ['计算单元', '文字单元']);
  const modes = await page.locator('.cell .input-mode').allTextContents();
  assert.equal(modes.length, 8);
  assert.ok(modes.every((mode, i) => mode === (i % 2 ? '计算单元' : '文字单元')));
  assert.ok((await page.locator('.cell').nth(3).locator('.cm-content').innerText()).length < 65);
  await page.getByRole('button', { name: '全部运行', exact: true }).click();
  await page.locator('.cell').last().locator('.result-meta').first().waitFor({ timeout: 60000 });
  assert.equal(await page.locator('.error-message').count(), 0);
  assert.equal(await page.locator('.js-plotly-plot').count(), 3);
  const animation = page.locator('.animation-output');
  await animation.scrollIntoViewIfNeeded();
  const toolbar = await page.locator('.toolbar').boundingBox();
  assert.ok(toolbar.y >= 0 && toolbar.y < 2, JSON.stringify(toolbar));
  assert.ok(await page.getByRole('button', { name: '全部运行', exact: true }).isVisible());
  await animation.getByTitle('播放动画').click();
  await page.waitForTimeout(750);
  await animation.getByTitle('暂停动画').click();
  const paused = Number(await animation.getByLabel('动画进度').inputValue());
  assert.ok(paused > 0);
  await page.waitForTimeout(200);
  assert.equal(Number(await animation.getByLabel('动画进度').inputValue()), paused);
  await animation.getByLabel('动画进度').fill('400');
  await page.waitForTimeout(100);
  const point = await animation.locator('.js-plotly-plot').evaluate(el => ({ x: el.data[2].x[0], y: el.data[2].y[0], trail: el.data[1].x.length }));
  assert.equal(point.trail, 401);
  assert.ok(point.x > 7 && point.y > 6, JSON.stringify(point));
  await page.screenshot({ path: 'work/ui/animation-desktop-0.1.2.png' });
  await animation.getByLabel('动画进度').fill('799');
  await animation.getByLabel('动画速度').selectOption('4');
  await animation.getByTitle('播放动画').click();
  await animation.getByTitle('播放动画').waitFor();
  assert.equal(await animation.getByLabel('动画进度').inputValue(), '800');
  await animation.getByLabel('循环').check();
  await animation.getByTitle('播放动画').click();
  await page.waitForTimeout(200);
  assert.ok(Number(await animation.getByLabel('动画进度').inputValue()) < 800);
  await animation.getByTitle('重置动画').click();
  assert.equal(await animation.getByLabel('动画进度').inputValue(), '0');

  await page.getByRole('button', { name: '计算示例', exact: true }).click();
  for (const group of ['解析求解', '数值求解', '后处理']) await page.getByRole('heading', { name: group, exact: true }).waitFor();
  await page.getByRole('button', { name: '显式数值计算', exact: true }).click();
  assert.equal(await page.locator('.cell').count(), 9);
  const numeric = page.locator('.cell').last();
  assert.match(await numeric.locator('.cm-content').innerText(), /^Column\[/);
  await numeric.getByTitle('运行单元').click();
  await numeric.locator('.group-item').nth(9).waitFor();
  assert.equal(await numeric.locator('.group-item').count(), 10);
  await page.getByTitle('关闭示例').click();

  const downloaded = page.waitForEvent('download');
  await page.locator('.document-actions').getByRole('button', { name: '另存为', exact: true }).click();
  const file = await downloaded;
  await file.saveAs('work/ui/animation-roundtrip.calix');
  await page.locator('input[type=file]').setInputFiles('work/ui/animation-roundtrip.calix');
  assert.equal(await page.locator('.cell').last().locator('.group-item').count(), 10);
  await page.locator('.notebook-list').getByRole('button', { name: '空气阻力下的二维抛体运动', exact: true }).first().click();
  await page.reload(); await page.locator('.animation-output').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.animation-output').scrollIntoViewIfNeeded();
  await page.getByLabel('动画进度').fill('400'); await page.waitForTimeout(200);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: 'work/ui/animation-mobile-0.1.3.png' });

  // A second animation mode updates complete frames rather than tracing a path.
  await page.setViewportSize({ width: 1360, height: 1000 });
  await page.getByRole('button', { name: '计算单元', exact: true }).click();
  const frameCell = page.locator('.cell').last();
  await frameCell.locator('.cm-content').fill('Animate[Plot[Sin[x-a],{x,-Pi,Pi}],{a,0,2 Pi}]');
  await frameCell.getByTitle('运行单元').click();
  await frameCell.locator('.animation-output').waitFor();
  const middleY = () => frameCell.locator('.js-plotly-plot').evaluate(el => el.data[0].y[100]);
  await frameCell.locator('.js-plotly-plot').waitFor();
  const before = await middleY();
  await frameCell.getByLabel('动画进度').fill('15');
  await page.waitForTimeout(150);
  assert.ok(Math.abs((await middleY()) - before) > 0.9);
  assert.deepEqual(errors, []);
  fs.writeFileSync('work/ui/workflow-report.json', JSON.stringify({ status: 'passed', animation: ['trajectory', 'frames'], stickyToolbar: true, groupedNumericalExamples: 10, saveAsRoundtrip: true, errors }, null, 2));
  await browser.close();
  console.log('Workflow UI passed: animation controls, frame changes, sticky toolbar, save-as, grouped results and mobile layout.');
})().catch(error => { console.error(error); process.exit(1); });
